# -*- coding: utf-8 -*-
"""生成 version_info.txt —— PyInstaller `--version-file` 用的 Windows 版本信息资源。

为什么中文要写成 \\uXXXX 转义：
  PyInstaller 读这个文件时会按 BOM/cookie 猜编码，猜错就把中文读成乱码。
  转义后文件是纯 ASCII，任何编码读进来都一样，eval 时再还原成中文。
  （模板里的注释也必须是英文，否则本脚本的 ASCII 校验会失败。）

改版本/改署名：只动下面 FIELDS 里的值，重跑本脚本即可。
打包时 build.bat 会自动带上 `--version-file version_info.txt`。
"""
import os
import sys

# GitHub Actions 的 Windows 机器控制台是 cp1252，中文 print 会直接
# UnicodeEncodeError 中断构建。这里把 stdout 强制成 UTF-8（幂等、失败不影响）。
try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass

TEMPLATE = '''# Windows version-info resource -- GENERATED by build_version.py, do not edit by hand.
# ASCII only: CJK text is written as \\uXXXX escapes, so it survives any decode attempt.
# LangID/Codepage 0804 / 04B0 = Simplified Chinese + Unicode.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=(@VER_TUPLE@),
    prodvers=(@VER_TUPLE@),
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable(
        '080404B0',
        [
          StringStruct('CompanyName', '@COMPANY@'),
          StringStruct('FileDescription', '@DESC@'),
          StringStruct('FileVersion', '@VER@'),
          StringStruct('InternalName', 'PDFBatchWatermark'),
          StringStruct('LegalCopyright', '@COPY@'),
          StringStruct('OriginalFilename', '@ORIG@'),
          StringStruct('ProductName', '@PROD@'),
          StringStruct('ProductVersion', '@VER@')
        ]
      )
    ]),
    VarFileInfo([VarStruct('Translation', [2052, 1200])])
  ]
)
'''

# ---- 只改这里 ----
FIELDS = {
    "@COMPANY@":   "©HB",
    "@DESC@":      "PDF 批量加水印 · 课件版权保护工具",
    "@VER@":       "1.0.0.0",
    "@VER_TUPLE@": "1, 0, 0, 0",
    "@COPY@":      "Copyright © 2026 HongBing. All rights reserved.",
    "@ORIG@":      "PDF批量加水印.exe",
    "@PROD@":      "PDF 批量加水印",
}


def esc(s):
    """中文 → \\uXXXX，保证输出是纯 ASCII。"""
    return s.encode("unicode_escape").decode("ascii").replace("\\x", "\\u00")


def main():
    txt = TEMPLATE
    for k, v in FIELDS.items():
        txt = txt.replace(k, esc(v) if k != "@VER_TUPLE@" else v)

    p = os.path.join(os.path.dirname(os.path.abspath(__file__)), "version_info.txt")
    txt.encode("ascii")  # 非 ASCII 会在这里直接抛错，防止写坏
    open(p, "w", encoding="ascii", newline="\n").write(txt)
    print("写出:", p, os.path.getsize(p), "字节")


if __name__ == "__main__":
    main()
